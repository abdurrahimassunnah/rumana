/**
 * Helper to get a smart, non-duplicate question from the bank
 */
export function getSmartAutoQuestion(type: ExerciseQuestionType, existingQuestionTexts: string[] = []): ExerciseQuestion {
  const bank = SYSTEM_QUESTION_BANK[type] || SYSTEM_QUESTION_BANK.short;
  
  // Try to find one not already present
  const available = bank.filter(q => !existingQuestionTexts.some(ext => ext.includes(q.question.substring(0, 15))));
  const selected = available.length > 0 ? available[Math.floor(Math.random() * available.length)] : bank[Math.floor(Math.random() * bank.length)];
  
  return {
    ...selected,
    id: `auto_q_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`
  };
}
